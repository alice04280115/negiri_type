# 商品名の語彙（generate_sentences.py が読む）。
# 書き方は「表記/よみ」をスペース区切りで並べる。よみはひらがな・ー・英小文字だけ（スペースや記号は入れない）。
#
# 商品ごとに次を書く。
#   l1    初級に入れる短い商品名（手で選んだもの。組み合わせはしない）
#   kinds 商品の種類。種類ごとに「組み合わせてよい語」だけを書く（書いていない組み合わせは作らない）
#           mods 前につく特徴　org 前につく産地　use 後ろにつく用途・味など　qty 後ろにつく量（量だけ違う名前は増やしすぎない）
#   long  達人の説明形の商品名の前半と、つないでよい種類の名前
#   en    達人の英字　sub 達人の副題。「表記/よみ/条件」の条件で使える名前を絞る
#           条件：k=種類（,区切り）　n=名前に入っていてほしい語　x=入っていてはいけない語（; で並べる）


def W(s):
    return [tuple(x.split('/')) for x in s.split()]


def E(s):
    """達人の英字。「英字/条件」（条件は副題と同じ書き方。なければどの種類にも使う）"""
    return [tuple((x + '/').split('/')[:2]) for x in s.split()]


def K(name, mods='', org='', use='', qty='', mu=True):
    """mu=False は「特徴＋用途・味」を組み合わせない（キャラメルポップコーンバター醤油味 のような食い違いを防ぐ）"""
    t, r = name.split('/')
    return dict(t=t, r=r, mods=W(mods), org=W(org), use=W(use), qty=W(qty), mu=mu)


def L(phrase, kinds):
    t, r = phrase.split('/')
    return dict(t=t, r=r, kinds=kinds.split())


